for lang, keys in new_keys.items():
    # Construct the string to inject
    inject_str = ""
    for k, v in keys.items():
        inject_str += f'    {k}: "{v}",\n'
    
    # Find the block for this language and insert before its closing brace
    pattern = r'(' + lang + r':\s*\{.*?)(\n\s*\})'
    content = re.sub(pattern, r'\1\n' + inject_str + r'\2', content, flags=re.DOTALL)

with open(file_path, "w", encoding="utf-8") as f:
    f.write(content)

